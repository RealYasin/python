# Display according to their number(Sunday being 1)

num=int(input("Enter Number(1 to 7)= "))
if num==1:
    print("It's Sunday")
elif num==2:
    print("It's Monday")
elif num==3:
    print("It's Tueday")
elif num==4:
    print("It's Wednesday")
elif num==5:
    print("It's Thursday")
elif num==6:
    print("It's Friday")
elif num==7:
    print("It's Saturday")
else:
    print("Please check the number you've entered, there are only 7 days in a week")
